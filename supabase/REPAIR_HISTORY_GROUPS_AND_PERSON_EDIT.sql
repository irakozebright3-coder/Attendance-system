-- AttendanceFlow: safe repair and feature migration
-- Run this file once in Supabase SQL Editor. Safe to re-run.
-- Preserves existing people, attendance records, groups and teams.

begin;

-- 1) Repair the existing person-edit error:
-- Some older deployments have an update trigger that expects this field.
alter table public.people
  add column if not exists updated_at timestamptz not null default now();

update public.people
set updated_at = coalesce(updated_at, created_at, now())
where updated_at is null;

alter table public.people
  alter column updated_at set default now(),
  alter column updated_at set not null;

create or replace function public.attendanceflow_touch_people_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists attendanceflow_people_updated_at on public.people;
create trigger attendanceflow_people_updated_at
before update on public.people
for each row execute function public.attendanceflow_touch_people_updated_at();

-- 2) Permanent attendance history, independent from the live register rows.
create table if not exists public.attendance_history (
  id bigint generated by default as identity primary key,
  team_id uuid not null references public.teams(id) on delete cascade,
  attendance_id uuid,
  person_id uuid,
  person_name text not null,
  attendance_date date not null,
  status text not null check (status in ('present','absent')),
  action text not null check (action in ('baseline','marked','changed','cleared')),
  marked_by uuid references auth.users(id) on delete set null,
  recorded_at timestamptz not null default now()
);

create index if not exists attendance_history_team_time_idx
  on public.attendance_history(team_id, recorded_at desc);
create index if not exists attendance_history_team_date_idx
  on public.attendance_history(team_id, attendance_date desc);
create unique index if not exists attendance_history_baseline_once_idx
  on public.attendance_history(attendance_id)
  where action = 'baseline' and attendance_id is not null;

alter table public.attendance_history enable row level security;
drop policy if exists attendance_history_team_read on public.attendance_history;
create policy attendance_history_team_read
on public.attendance_history
for select to authenticated
using (public.is_team_member(team_id));
grant select on public.attendance_history to authenticated;

-- Capture changes made through the existing attendance upsert/delete flow.
create or replace function public.attendanceflow_capture_attendance_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_person_name text;
begin
  if tg_op = 'INSERT' then
    select p.name into v_person_name
    from public.people p
    where p.id = new.person_id and p.team_id = new.team_id;

    insert into public.attendance_history
      (team_id, attendance_id, person_id, person_name, attendance_date, status, action, marked_by, recorded_at)
    values
      (new.team_id, new.id, new.person_id, coalesce(v_person_name, 'Unknown person'),
       new.date, new.status, 'marked', new.marked_by, coalesce(new.marked_at, now()));
    return new;
  elsif tg_op = 'UPDATE' then
    -- Do not create duplicate history entries for irrelevant updates.
    if old.status is not distinct from new.status
       and old.person_id is not distinct from new.person_id
       and old.date is not distinct from new.date then
      return new;
    end if;

    select p.name into v_person_name
    from public.people p
    where p.id = new.person_id and p.team_id = new.team_id;

    insert into public.attendance_history
      (team_id, attendance_id, person_id, person_name, attendance_date, status, action, marked_by, recorded_at)
    values
      (new.team_id, new.id, new.person_id, coalesce(v_person_name, 'Unknown person'),
       new.date, new.status, 'changed', new.marked_by, coalesce(new.marked_at, now()));
    return new;
  else
    select p.name into v_person_name
    from public.people p
    where p.id = old.person_id and p.team_id = old.team_id;

    insert into public.attendance_history
      (team_id, attendance_id, person_id, person_name, attendance_date, status, action, marked_by, recorded_at)
    values
      (old.team_id, old.id, old.person_id,
       coalesce(v_person_name, 'Removed person (' || old.person_id::text || ')'),
       old.date, old.status, 'cleared', old.marked_by, now());
    return old;
  end if;
end;
$$;

drop trigger if exists attendanceflow_capture_attendance_history on public.attendance;
create trigger attendanceflow_capture_attendance_history
after insert or update or delete on public.attendance
for each row execute function public.attendanceflow_capture_attendance_history();

-- Seed a baseline for existing attendance rows, without duplicating on reruns.
insert into public.attendance_history
  (team_id, attendance_id, person_id, person_name, attendance_date, status, action, marked_by, recorded_at)
select a.team_id, a.id, a.person_id, coalesce(p.name, 'Unknown person'),
       a.date, a.status, 'baseline', a.marked_by, coalesce(a.marked_at, a.updated_at, now())
from public.attendance a
left join public.people p on p.id = a.person_id and p.team_id = a.team_id
where not exists (
  select 1 from public.attendance_history h
  where h.attendance_id = a.id and h.action = 'baseline'
);

-- 3) Committee-style groups, called "Groups" in the UI.
create table if not exists public.team_groups (
  id uuid primary key default gen_random_uuid(),
  team_id uuid not null references public.teams(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 80),
  description text not null default '',
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, team_id)
);

create unique index if not exists team_groups_team_name_unique_idx
  on public.team_groups(team_id, lower(btrim(name)));
create index if not exists team_groups_team_idx
  on public.team_groups(team_id, name);

create unique index if not exists people_id_team_unique_idx
  on public.people(id, team_id);

create table if not exists public.team_group_members (
  team_id uuid not null,
  group_id uuid not null,
  person_id uuid not null,
  created_at timestamptz not null default now(),
  primary key (group_id, person_id),
  constraint team_group_members_group_team_fk
    foreign key (group_id, team_id)
    references public.team_groups(id, team_id) on delete cascade,
  constraint team_group_members_person_team_fk
    foreign key (person_id, team_id)
    references public.people(id, team_id) on delete cascade
);

create index if not exists team_group_members_team_group_idx
  on public.team_group_members(team_id, group_id);

alter table public.team_groups enable row level security;
alter table public.team_group_members enable row level security;

drop policy if exists team_groups_team_read on public.team_groups;
create policy team_groups_team_read on public.team_groups
for select to authenticated
using (public.is_team_member(team_id));

drop policy if exists team_groups_admin_insert on public.team_groups;
create policy team_groups_admin_insert on public.team_groups
for insert to authenticated
with check (public.is_team_admin(team_id));

drop policy if exists team_groups_admin_update on public.team_groups;
create policy team_groups_admin_update on public.team_groups
for update to authenticated
using (public.is_team_admin(team_id))
with check (public.is_team_admin(team_id));

drop policy if exists team_groups_admin_delete on public.team_groups;
create policy team_groups_admin_delete on public.team_groups
for delete to authenticated
using (public.is_team_admin(team_id));

drop policy if exists team_group_members_team_read on public.team_group_members;
create policy team_group_members_team_read on public.team_group_members
for select to authenticated
using (public.is_team_member(team_id));

drop policy if exists team_group_members_admin_insert on public.team_group_members;
create policy team_group_members_admin_insert on public.team_group_members
for insert to authenticated
with check (public.is_team_admin(team_id));

drop policy if exists team_group_members_admin_delete on public.team_group_members;
create policy team_group_members_admin_delete on public.team_group_members
for delete to authenticated
using (public.is_team_admin(team_id));

grant select, insert, update, delete on public.team_groups to authenticated;
grant select, insert, delete on public.team_group_members to authenticated;

