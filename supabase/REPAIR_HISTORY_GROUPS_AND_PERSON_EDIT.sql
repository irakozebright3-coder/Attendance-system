create or replace function public.save_team_group(
  p_team_id uuid,
  p_group_id uuid,
  p_name text,
  p_description text default '',
  p_person_ids uuid[] default '{}'::uuid[]
)
returns public.team_groups
language plpgsql
security definer
set search_path = public
as $$
declare
  v_group public.team_groups;
  v_ids uuid[] := coalesce(p_person_ids, '{}'::uuid[]);
  v_requested_count integer;
  v_valid_count integer;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if not public.is_team_admin(p_team_id) then
    raise exception 'Only a team owner or admin can manage groups';
  end if;
  if p_name is null or length(btrim(p_name)) < 1 or length(btrim(p_name)) > 80 then
    raise exception 'Group name must contain between 1 and 80 characters';
  end if;
  if length(coalesce(p_description, '')) > 400 then
    raise exception 'Group description must be 400 characters or fewer';
  end if;

  select count(distinct x)::integer into v_requested_count
  from unnest(v_ids) as ids(x);
  select count(*)::integer into v_valid_count
  from public.people p
  where p.team_id = p_team_id and p.id = any(v_ids);

  if v_requested_count <> v_valid_count then
    raise exception 'One or more selected people do not belong to this team';
  end if;

  if p_group_id is null then
    insert into public.team_groups(team_id, name, description, created_by)
    values (p_team_id, btrim(p_name), coalesce(btrim(p_description), ''), auth.uid())
    returning * into v_group;
  else
    update public.team_groups
    set name = btrim(p_name),
        description = coalesce(btrim(p_description), ''),
        updated_at = now()
    where id = p_group_id and team_id = p_team_id
    returning * into v_group;

    if not found then
      raise exception 'Group not found in this team';
    end if;
  end if;

  delete from public.team_group_members
  where team_id = p_team_id and group_id = v_group.id;

  insert into public.team_group_members(team_id, group_id, person_id)
  select p_team_id, v_group.id, p.id
  from public.people p
  where p.team_id = p_team_id and p.id = any(v_ids)
  on conflict (group_id, person_id) do nothing;

  return v_group;
end;
$$;

revoke all on function public.save_team_group(uuid, uuid, text, text, uuid[]) from public;
revoke all on function public.save_team_group(uuid, uuid, text, text, uuid[]) from anon;
grant execute on function public.save_team_group(uuid, uuid, text, text, uuid[]) to authenticated;

-- Enable realtime notifications for the new team-scoped tables when the
-- standard Supabase realtime publication exists.
do $
declare
  table_name text;
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    foreach table_name in array array['attendance_history','team_groups','team_group_members'] loop
      if not exists (
        select 1 from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = table_name
      ) then
        execute format('alter publication supabase_realtime add table public.%I', table_name);
      end if;
    end loop;
  end if;
end;
$;

commit;
