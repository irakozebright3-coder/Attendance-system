create or replace function public.platform_list_team_members(p_team_id uuid)
returns table (
  user_id uuid,
  email text,
  role text,
  joined_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $af_platform_list_team_members$
  select u.id, u.email::text, tm.role, tm.joined_at
  from public.team_members tm
  join auth.users u on u.id = tm.user_id
  where tm.team_id = p_team_id
    and public.is_platform_admin()
  order by tm.joined_at;
$af_platform_list_team_members$;

grant execute on function public.platform_list_team_members(uuid) to authenticated;
revoke all on function public.platform_list_team_members(uuid) from public;
revoke all on function public.platform_list_team_members(uuid) from anon;

