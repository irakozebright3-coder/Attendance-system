-- TEST-ONLY: reproduce the live project's legacy attendance_history shape
-- (status/person_name NOT NULL, present/absent check) BEFORE schema.sql runs,
-- so the test proves the upgrade path, not just a fresh install.
create table if not exists public.attendance_history (
  id bigint generated by default as identity primary key,
  team_id uuid not null,
  attendance_id uuid,
  person_id uuid,
  person_name text not null,
  attendance_date date not null,
  status text not null check (status in ('present','absent')),
  action text not null default 'marked' check (action in ('baseline','marked','changed','cleared')),
  marked_by uuid,
  recorded_at timestamptz not null default now()
);
